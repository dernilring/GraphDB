CREATE TABLE Клиент (
    КодКлиента        INT            NOT NULL PRIMARY KEY,
    НазваниеКомпании  NVARCHAR(50)   NOT NULL,
    Отрасль           NVARCHAR(50)   NOT NULL,
    Фамилия           NVARCHAR(30)   NOT NULL,
    Имя               NVARCHAR(30)   NOT NULL,
    Отчество          NVARCHAR(30),
    Бюджет            MONEY,
    Город             NVARCHAR(30),
    ДатаРегистрации   DATETIME       NOT NULL
) AS NODE;

CREATE TABLE Кампания (
    КодКампании   INT           NOT NULL PRIMARY KEY,
    Название      NVARCHAR(30)  NOT NULL,
    Цель          NVARCHAR(30),
    ДатаНачала    DATETIME      NOT NULL,
    ДатаОкончания DATETIME,
    Бюджет        MONEY         NOT NULL,
    Статус        NVARCHAR(20)  NOT NULL
) AS NODE;

CREATE TABLE Канал (
    КодКанала              INT           NOT NULL PRIMARY KEY,
    Название               NVARCHAR(30)  NOT NULL,
    Тип                    NVARCHAR(20)  NOT NULL,
    Платформа              NVARCHAR(20),
    ОхватАудитории         INT,
    СтоимостьЗа1000Показов MONEY
) AS NODE;

CREATE TABLE Менеджер (
    КодМенеджера  INT           NOT NULL PRIMARY KEY,
    Фамилия       NVARCHAR(20)  NOT NULL,
    Имя           NVARCHAR(20)  NOT NULL,
    Отчество      NVARCHAR(20),
    Телефон       NVARCHAR(20)  NOT NULL,
    Должность     NVARCHAR(30)  NOT NULL
) AS NODE;

CREATE TABLE Креатив (
    КодКреатива   INT           NOT NULL PRIMARY KEY,
    Название      NVARCHAR(30)  NOT NULL,
    Формат        NVARCHAR(20)  NOT NULL,
    ДатаСоздания  DATETIME      NOT NULL,
    Статус        NVARCHAR(20)  NOT NULL
) AS NODE;

CREATE TABLE Контракт (
    КодКонтракта    INT       NOT NULL PRIMARY KEY,
    ДатаПодписания  DATETIME  NOT NULL,
    Сумма           MONEY     NOT NULL,
    СрокДействия    DATETIME,
    СтатусОплаты    NVARCHAR(20)
) AS NODE;

CREATE TABLE ЦелеваяАудитория (
    КодАудитории     INT           NOT NULL PRIMARY KEY,
    НазваниеСегмента NVARCHAR(30)  NOT NULL,
    Интересы         NVARCHAR(70),
    География        NVARCHAR(50),
    ВозрастОт        INT,
    ВозрастДо        INT
) AS NODE;
-- пункт 2

CREATE TABLE Заказывает (
    ДатаЗаказа  DATETIME      NOT NULL,
    Сумма       MONEY         NOT NULL,
    Приоритет   NVARCHAR(10),
    CONSTRAINT EC_Заказывает CONNECTION (Клиент TO Кампания)
) AS EDGE;

CREATE TABLE Использует (
    ДатаРазмещения    DATETIME      NOT NULL,
    Бюджет            MONEY         NOT NULL,
    КоличествоПоказов INT,
    CTR               DECIMAL(5,2),
    CONSTRAINT EC_Использует CONNECTION (Кампания TO Канал)
) AS EDGE;

CREATE TABLE Ведет (
    ДатаНазначения  DATETIME      NOT NULL,
    Роль            NVARCHAR(30)  NOT NULL,
    CONSTRAINT EC_Ведет CONNECTION (Менеджер TO Кампания)
) AS EDGE;

CREATE TABLE Включает (
    ДатаДобавления  DATETIME      NOT NULL,
    Статус          NVARCHAR(20)  NOT NULL,
    CONSTRAINT EC_Включает CONNECTION (Кампания TO Креатив)
) AS EDGE;

CREATE TABLE НаправленаНа (
    ОжидаемыйОхват  INT,
    Приоритет       NVARCHAR(10)  NOT NULL,
    CONSTRAINT EC_НаправленаНа CONNECTION (Кампания TO ЦелеваяАудитория)
) AS EDGE;

CREATE TABLE ОформленПо (
    ДатаПодписания  DATETIME      NOT NULL,
    СтатусОплаты    NVARCHAR(20)  NOT NULL,
    CONSTRAINT EC_ОформленПо CONNECTION (Клиент TO Контракт)
) AS EDGE;

CREATE TABLE СвязанаС (
    ДатаСвязи DATETIME NOT NULL,
    CONSTRAINT EC_СвязанаС CONNECTION (Кампания TO Кампания)
) AS EDGE;
