FROM Клиент кл, Заказывает з, Кампания кп, Использует и, Канал кн
WHERE MATCH(кл-(з)->кп-(и)->кн);

SELECT м.Фамилия + ' ' + м.Имя AS Менеджер, кп.Название AS Кампания, кн.Название AS Канал, и.CTR
FROM Менеджер м, Ведет в, Кампания кп, Использует и, Канал кн
WHERE MATCH(м-(в)->кп-(и)->кн)
ORDER BY и.CTR DESC;

SELECT кл.НазваниеКомпании AS Клиент, кп.Название AS Кампания, ца.НазваниеСегмента AS Аудитория, ца.География
FROM Клиент кл, Заказывает з, Кампания кп, НаправленаНа н, ЦелеваяАудитория ца
