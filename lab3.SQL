SELECT
    c1.Название AS StartCampaign,
    LAST_VALUE(c2.Название) WITHIN GROUP (GRAPH PATH) AS EndCampaign,
    COUNT(c2.Название) WITHIN GROUP (GRAPH PATH) AS PathLength
FROM
    Кампания c1,
    СвязанаС FOR PATH sc,
    Кампания FOR PATH c2
WHERE
    MATCH(SHORTEST_PATH(c1(-(sc)->c2)+))
    AND c1.КодКампании = 1
    AND LAST_VALUE(c2.Название) WITHIN GROUP (GRAPH PATH) IS NOT NULL;

SELECT
    c1.Название AS StartCampaign,
    LAST_VALUE(c2.Название) WITHIN GROUP (GRAPH PATH) AS EndCampaign,
